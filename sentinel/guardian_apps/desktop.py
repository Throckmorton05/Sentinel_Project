SYSTEM_APP_DIRS = (
    Path('/usr/local/share/applications'), Path('/usr/share/applications'),
    Path('/var/lib/flatpak/exports/share/applications'),
    Path('/var/lib/snapd/desktop/applications'),
)
OVERRIDE_DIR = Path('/usr/local/share/applications')
MARKER = '# Generated by Sentinel Guardian App Access\n'
RECOVERY_ID = 'sentinel-guardian-access.desktop'
RECOVERY_EXEC = '/usr/lib/sentinel/venv/bin/python -I -m sentinel.guardian_apps.manager'
WEBSITE_MANAGER_EXEC = '/usr/lib/sentinel/venv/bin/python -I -m sentinel.guardian_websites.manager'
PORTAL_EXEC = '/usr/lib/sentinel/venv/bin/python -I -B -m sentinel.portal.main'
GUIDE_EXEC = PORTAL_EXEC + ' --guide'
# These programs are session plumbing, not applications a guardian can revoke.
SESSION_PROGRAMS = frozenset({
    'plasmashell', 'kwin_wayland', 'kwin_x11', 'ksmserver', 'kded6',
    'kaccess', 'kglobalacceld', 'kscreenlocker_greet', 'plasma_session',
    'startplasma-wayland', 'startplasma-x11', 'ksplashqml', 'ksplashsimple',
    'plasma_renderer', 'plasma-renderer', 'plasmawindowed',
    'nm-applet', 'blueman-applet', 'kdeconnectd', 'knotify6',
    'gmenudbusmenuproxy', 'xembedsniproxy',
    'xdg-desktop-portal', 'xdg-desktop-portal-kde', 'polkit-kde-authentication-agent-1',
})
SETTINGS_PROGRAMS = frozenset({'systemsettings', 'systemsettings6', 'systemsettings5'})
SETTINGS_HOST_PROGRAMS = frozenset({'kcmshell6', 'kcmshell5'})
DEFAULT_PROGRAMS = SETTINGS_PROGRAMS | {'dolphin'}


def is_session_executable(executable: str | None) -> bool:
    if not executable:
        return False
    path = Path(executable).resolve()
    # Helpers installed beneath libexec are not standalone applications.
    if path.name in SETTINGS_PROGRAMS | SETTINGS_HOST_PROGRAMS:
        return False  # GUI settings-window hosts, not background services.
    return path.name in SESSION_PROGRAMS or 'libexec' in path.parts


def is_default(entry: dict) -> bool:
    return entry['type'] == 'native' and Path(entry.get('executable') or '').name in DEFAULT_PROGRAMS


def runtime_executables(entry: dict) -> set[str]:
    if entry['type'] != 'native' or not entry.get('executable'):
        return set()
    result = {entry['executable']}
    if Path(entry['executable']).name in SETTINGS_PROGRAMS:
        # Standalone settings modules share this GUI host; associate it with
        # System Settings rather than offering dozens of separate KCM pages.
        result.update(settings_executables())
    return result


def settings_executables() -> set[str]:
    """Resolve installed GUI hosts independently of menu/launcher visibility.

    Match protected executable paths, never process names or arbitrary user
    files. KDE panels, direct launches and D-Bus activation use these same hosts.
    """
    result = set()
    for program in SETTINGS_PROGRAMS | SETTINGS_HOST_PROGRAMS:
        executable = canonical(program)
        if (executable and Path(executable).name in SETTINGS_PROGRAMS | SETTINGS_HOST_PROGRAMS
                and protected_path(Path(executable))):
            result.add(executable)
    return result


# Blocking a shared interpreter/launcher would also kill Sentinel or approved apps.
SHARED_RUNNERS = {'python', 'python3', 'bash', 'sh', 'env', 'flatpak',
                  'java', 'node', 'ruby', 'perl', 'wine', 'bwrap', 'snap', 'dash'}
BUILTIN_IDS = frozenset({'sentinel-guardian-access.desktop', 'sentinel-guardian-websites.desktop',
                         'sentinel-portal.desktop', 'sentinel-getting-started.desktop'})
LEGACY_MANAGER_IDS = frozenset({'sentinel-guardian-access.desktop', 'sentinel-guardian-websites.desktop'})


def protected_path(path: Path) -> bool:
    """Only immutable-to-the-desktop-user system executables may be approved."""
    try:
        path = path.resolve(strict=True)
        for part in (path, *path.parents):
            info = part.stat()
            if info.st_uid != 0 or info.st_mode & 0o022:
                return False
        if not path.is_file() or not os.access(path, os.X_OK):
            return False
        with path.open('rb') as stream:
            magic = stream.read(4)
            return magic == b'\x7fELF' or magic.startswith(b'#!')
    except OSError:
        return False


def canonical(executable: str) -> str | None:
    resolved = shutil.which(executable, path='/usr/local/bin:/usr/bin:/bin:/usr/games')
    if not resolved:
        return None
    path = str(Path(resolved).resolve())
    # Common trusted launch scripts have separate, stable runtime executables.
    wrappers = {
        '/opt/google/chrome/google-chrome': '/opt/google/chrome/chrome',
        '/usr/lib/libreoffice/program/soffice': '/usr/lib/libreoffice/program/soffice.bin',
        '/usr/bin/firefox': '/usr/lib/firefox/firefox',
        '/usr/bin/firefox-esr': '/usr/lib/firefox-esr/firefox-esr',
    }
    target = wrappers.get(path)
    return target if target and Path(target).is_file() else path


def is_system_steam_launcher(executable: str | Path | None) -> bool:
    """Recognize protected Steam wrappers even when a symlink renames them."""
    if not executable:
        return False
    target = Path(executable).resolve()
    if (target.name in SHARED_RUNNERS | SESSION_PROGRAMS or target.name.startswith('python')
            or not protected_path(target)):
        return False
    if target.name in {'steam', 'steam-launcher', 'steam.sh', 'bin_steam.sh'}:
        return True
    installed = canonical('steam')
    return bool(installed and Path(installed).resolve() == target)


SNAP_INSTANCE_RE = re.compile(r'[a-z0-9][a-z0-9-]*(?:_[a-z0-9]+)?')
APP_ID_RE = re.compile(r'[A-Za-z_][A-Za-z0-9_-]*(?:\.[A-Za-z_][A-Za-z0-9_-]*){2,}')
ASSIGNMENT_RE = re.compile(r'[A-Za-z_][A-Za-z0-9_]*=.*', re.DOTALL)


def user_home(uid: int | None) -> Path | None:
    try:
        return Path(pwd.getpwuid(uid).pw_dir) if uid is not None else None
    except KeyError:
        return None


def _readable(info, uid: int, groups: set[int], mask: int) -> bool:
    shift = 6 if info.st_uid == uid else 3 if info.st_gid in groups else 0
    return bool((info.st_mode >> shift) & mask)


def read_launcher(path: Path, uid: int | None = None) -> str:
    """Bounded regular-file reads; user launchers cannot expose root-private files.

    Check the opened inode and its actual kernel-reported path for ordinary DAC
    accessibility before reading user content with the daemon's privileges.
    ACL-only grants are conservatively omitted rather than granting extra access.
    """
    fd = os.open(path.resolve(), os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, 'r', encoding='utf-8') as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode):
            raise ValueError('Launcher must be a regular file.')
        if uid is not None:
            user = pwd.getpwuid(uid)
            groups = set(os.getgrouplist(user.pw_name, user.pw_gid))
            actual = Path(os.readlink(f'/proc/self/fd/{stream.fileno()}'))
            if not _readable(info, uid, groups, 4) or any(
                    not _readable(parent.stat(), uid, groups, 1) for parent in actual.parents):
                raise PermissionError('Launcher is not readable by the protected user.')
        source = stream.read(262145)
        if len(source) > 262144:
            raise ValueError('Launcher exceeds size limit.')
        return source


def _without_env(argv: list[str]) -> list[str]:
    if not argv or Path(argv[0]).name != 'env':
        return argv
    tokens = argv[1:]
    while tokens and (tokens[0] == '--' or ASSIGNMENT_RE.fullmatch(tokens[0])):
        tokens = tokens[1:]
    return tokens


def normalize_exec(argv: list[str]) -> tuple[list[str], list[str]]:
    """Recognize Steam's simple shell wrapper without accepting shell programs."""
    tokens = _without_env(argv)
    if (len(tokens) == 3 and Path(tokens[0]).name in {'sh', 'bash', 'dash'} and tokens[1] == '-c'):
        inner = shlex.split(tokens[2])
        assignments = []
        while inner and ASSIGNMENT_RE.fullmatch(inner[0]):
            assignments.append(inner.pop(0))
        if inner and inner[0] == 'exec':
            inner = inner[1:]
        # This adapter accepts only one Steam command plus desktop file fields.
        if (inner and Path(inner[0]).name in {'steam', 'steam.sh'}
                and all(value in {'%U', '%u', '%F', '%f'} for value in inner[1:])):
            prefix = argv[:len(argv) - len(tokens)]
            argv = prefix + (['/usr/bin/env', *assignments, *inner] if assignments else inner)
            tokens = inner
    return argv, tokens


def steam_roots(uid: int | None) -> list[Path]:
    home = user_home(uid)
    if home is None:
        return []
    candidates = [home / '.local/share/Steam', home / '.steam/debian-installation',
                  home / '.steam/steam', home / '.steam/root', home / 'Steam']
    return list(dict.fromkeys(path.resolve() for path in candidates))


def is_steam_path(executable: str | None, uid: int | None, *, roots=None) -> bool:
    if not executable:
        return False
    path = Path(executable).resolve()
    for root in steam_roots(uid) if roots is None else roots:
        try:
            relative = path.relative_to(root)
        except ValueError:
            continue
        if str(relative) in {'steam.sh', 'ubuntu12_32/steam', 'ubuntu12_64/steam'}:
            return True
    return False


def steam_runtime(executable: str | None, uid: int | None, *, roots=None) -> bool:
    roots = steam_roots(uid) if roots is None else roots
    if is_steam_path(executable, uid, roots=roots):
        return True
    if not executable or Path(executable).name != 'steamwebhelper':
        return False
    return any(Path(executable).resolve().is_relative_to(root) for root in roots)


def interpreter_script(proc) -> str | None:
    """Match the script operand, never any argument containing a script filename."""
    if Path(proc.info.get('exe') or '').name not in {'sh', 'bash', 'dash', 'python3', 'python3.14'}:
        return None
    command = proc.cmdline()
    if not isinstance(command, list):
        return None
    values = command[1:]
    while values and values[0].startswith('-'):
        if values[0] in {'-c', '-m', '-'}:
            return None
        if values[0] not in {'--', '-u', '-e', '-x', '-B', '-E', '-I', '-O', '-s', '-S', '-v', '-q', '--noprofile', '--norc'}:
            return None
        values = values[1:]
    return str(Path(values[0]).resolve()) if values and values[0].startswith('/') else None


def snap_process(proc) -> str | None:
    """Use kernel confinement metadata or the mounted executable path, not env."""
    try:
        label = Path(f'/proc/{proc.pid}/attr/current').read_text().split()[0]
        if label.startswith('snap.'):
            instance = label.split('.', 2)[1]
            if SNAP_INSTANCE_RE.fullmatch(instance):
                return instance
    except (OSError, IndexError):
        pass
    parts = Path(proc.info.get('exe') or '').parts
    if len(parts) > 3 and parts[1] == 'snap' and SNAP_INSTANCE_RE.fullmatch(parts[2]):
        return parts[2]
    return None


def is_settings_module(entry, desktop_id: str) -> bool:
    services = entry.get('X-KDE-ServiceTypes', '') + ';' + entry.get('ServiceTypes', '')
    return bool('KCModule' in services.split(';') or desktop_id.startswith(('kcm_', 'kcm-'))
                or entry.get('X-KDE-System-Settings-Parent-Category')
                or entry.get('X-KDE-System-Settings-Parent-Category-V2')
                or entry.get('X-KDE-ParentApp') in {'kcontrol', 'systemsettings'})


def parse_launcher(path: Path, desktop_id: str, *, include_settings_modules=False, include_hidden=False, uid=None, user_source=False) -> dict | None:
    try:
        # Bound reads, including malformed/untrusted user launchers.
        source = read_launcher(path, uid if user_source else None)
        if len(source) > 262144 or source.startswith(MARKER):
            return None
        parser = configparser.ConfigParser(interpolation=None, strict=False)
        parser.optionxform = str
        parser.read_string(source)
        entry = parser['Desktop Entry']
        if entry.get('Type') != 'Application' or (not include_hidden and entry.get('Hidden', '').lower() == 'true'):
            return None
        settings_module = is_settings_module(entry, desktop_id)
        if settings_module and not include_settings_modules:
            return None
        if desktop_id not in BUILTIN_IDS:
            # Only launchers normally visible in this KDE session are app choices.
            if ((not include_hidden and entry.get('NoDisplay', '').lower() == 'true' and not settings_module)
                    or entry.get('Terminal', '').lower() == 'true'):
                return None
            only = set(entry.get('OnlyShowIn', '').split(';')) - {''}
            if (only and 'KDE' not in only) or 'KDE' in entry.get('NotShowIn', '').split(';'):
                return None
            if 'X-KDE-autostart-phase' in entry:
                return None
        argv, tokens = normalize_exec(shlex.split(entry.get('Exec', '')))
        exe = canonical(tokens[0]) if tokens else None
        if desktop_id not in BUILTIN_IDS and is_session_executable(exe) and not is_system_steam_launcher(exe):
            return None
        flatpak_id = entry.get('X-Flatpak')
        if not flatpak_id and len(tokens) >= 3 and Path(tokens[0]).name == 'flatpak' and tokens[1] == 'run':
            flatpak_id = next((t for t in tokens if APP_ID_RE.fullmatch(t)), None)
        snap_instance = None
        if tokens and Path(tokens[0]).parent == Path('/snap/bin'):
            snap_instance = Path(tokens[0]).name.split('.', 1)[0]
        elif tokens and Path(tokens[0]).name == 'snap' and len(tokens) >= 3 and tokens[1] == 'run':
            snap_instance = tokens[2].split('.', 1)[0] if not tokens[2].startswith('-') else None
        hint = entry.get('X-SnapInstanceName')
        snap_runner = canonical('snap')
        valid_snap = bool(snap_instance and SNAP_INSTANCE_RE.fullmatch(snap_instance)
                          and (not hint or hint == snap_instance) and exe == snap_runner
                          and exe and protected_path(Path(exe)))
        valid_flatpak = bool(flatpak_id and APP_ID_RE.fullmatch(flatpak_id) and tokens
                             and len(tokens) >= 3 and Path(tokens[0]).name == 'flatpak'
                             and tokens[1] == 'run' and flatpak_id in tokens
                             and exe == canonical('flatpak') and exe and protected_path(Path(exe)))
        kind = 'snap' if valid_snap else 'flatpak' if valid_flatpak else 'native'
        if kind == 'native' and exe and Path(tokens[0]).name in {'steam', 'steam.sh'}:
            # /usr/games is not in every desktop session's PATH.
            argv = [exe if token == tokens[0] else token for token in argv]
        steam = bool(is_system_steam_launcher(exe) or is_steam_path(exe, uid))
        supported = bool(valid_snap or valid_flatpak or (exe and protected_path(Path(exe))) or steam)
        if kind == 'native' and exe:
            basename = Path(exe).name
            if basename in SHARED_RUNNERS or basename.startswith('python') or (is_session_executable(exe) and not steam):
                supported = False
        if (hint and not valid_snap) or (flatpak_id and not valid_flatpak):
            supported = False  # Package hints cannot disguise an unrelated command.
        result = dict(desktop_id=desktop_id, name=entry.get('Name', desktop_id),
                      type=kind, executable=exe if kind == 'native' else None,
                      flatpak_id=flatpak_id if kind == 'flatpak' else None,
                      snap_instance=snap_instance if kind == 'snap' else None,
                      supported=supported, source=source, path=str(path), argv=argv,
                      menu_hidden=entry.get('Hidden', '').lower() == 'true' or entry.get('NoDisplay', '').lower() == 'true',
                      settings_module=settings_module, runtime_family='steam' if steam and kind == 'native' else None)
        if user_source:
            result['launcher_hash'] = hashlib.sha256(json.dumps(argv, ensure_ascii=True).encode()).hexdigest()
        return result
    except (OSError, UnicodeError, ValueError, configparser.Error, KeyError):
        return None


def discover(directories=None, *, include_settings_modules=False, include_hidden=False, uid=None) -> dict[str, dict]:
    result = {}
    seen = set()
    user_dirs = []
    home = user_home(uid)
    if home is not None and directories is None:
        user_dirs = [home / '.local/share/applications', home / '.local/share/flatpak/exports/share/applications']
    roots = [*user_dirs, *SYSTEM_APP_DIRS] if directories is None else directories
    for directory in roots:
        try:
            paths = sorted(directory.rglob('*.desktop')) if directory.is_dir() else []
        except OSError:
            continue
        for path in paths:
            desktop_id = str(path.relative_to(directory)).replace('/', '-')
            if directory in user_dirs and desktop_id in BUILTIN_IDS:
                continue  # Recovery launchers must come from the system install.
            if desktop_id in seen:
                continue
            try:
                if read_launcher(path, uid if directory in user_dirs else None).startswith(MARKER):
                    continue  # Our override must not hide its original source.
            except (OSError, UnicodeError, ValueError, KeyError):
                continue
            entry = parse_launcher(path, desktop_id, include_settings_modules=include_settings_modules,
                                   include_hidden=include_hidden, uid=uid, user_source=directory in user_dirs)
            # A menu-only tombstone must not hide the installed executable from
            # the blocking picker. Guardian menu discovery keeps XDG precedence.
            if not include_hidden or entry and entry.get('argv'):
                seen.add(desktop_id)
            if entry:
                if not include_hidden or entry.get('argv'):
                    result[desktop_id] = entry
    return result


SNAP_MOUNT_ROOT = Path('/snap')


def blocking_fallbacks() -> dict[str, dict]:
    """Installed package choices when no normal menu launcher is available.

    Snap's mounted GUI metadata is independent of exported desktop launchers.
    These are blocking identities only, never commands to execute or approve.
    """
    entries = {}
    try:
        packages = sorted(SNAP_MOUNT_ROOT.iterdir())
    except OSError:
        packages = []
    for package in packages:
        if not SNAP_INSTANCE_RE.fullmatch(package.name):
            continue
        current = package / 'current'
        if not (current / 'meta/snap.yaml').is_file():
            continue
        try:
            launchers = sorted((current / 'meta/gui').glob('*.desktop'))
        except OSError:
            continue
        for path in launchers:
            try:
                source = read_launcher(path)
                parser = configparser.ConfigParser(interpolation=None, strict=False)
                parser.optionxform = str
                parser.read_string(source)
                entry = parser['Desktop Entry']
                if entry.get('Type') != 'Application' or entry.get('Terminal', '').lower() == 'true':
                    continue
                icon = entry.get('Icon', '').replace('${SNAP}', str(current))
                entry['Icon'] = icon
                import io
                rendered = io.StringIO()
                parser.write(rendered, space_around_delimiters=False)
                key = 'sentinel-detected-snap-' + package.name + '-' + path.name
                entries[key] = dict(desktop_id=key, name=entry.get('Name', package.name),
                    type='snap', snap_instance=package.name, executable=None, flatpak_id=None,
                    supported=True, runtime_family=None, source=rendered.getvalue(), path=str(path))
            except (OSError, UnicodeError, ValueError, configparser.Error, KeyError):
                continue
    steam = canonical('steam')  # Includes /usr/games, even outside root's PATH.
    if is_system_steam_launcher(steam):
        key = 'sentinel-detected-steam.desktop'
        entries[key] = dict(desktop_id=key, name='Steam', type='native', executable=steam,
            flatpak_id=None, snap_instance=None, supported=True, runtime_family='steam',
            source='[Desktop Entry]\nType=Application\nName=Steam\nIcon=steam\n', path=steam)
    return entries


def render_launcher(entry: dict, allowed: bool) -> str:
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    parser.optionxform = str
    parser.read_string(entry['source'])
    desktop = parser['Desktop Entry']
    desktop['Hidden'] = 'false' if allowed else 'true'
    desktop['NoDisplay'] = 'true' if (entry.get('settings_module') or not allowed
                                   or entry['desktop_id'] in LEGACY_MANAGER_IDS) else 'false'
    desktop['DBusActivatable'] = 'false'  # Prevent bypassing the launch gate.
    # Built-in management windows have fixed installed entry points. Never
    # copy launcher-supplied commands or put recovery behind the daemon.
    desktop['Exec'] = (GUIDE_EXEC if entry['desktop_id'] == 'sentinel-getting-started.desktop' else
                       PORTAL_EXEC if entry['desktop_id'] == 'sentinel-portal.desktop' else
                       WEBSITE_MANAGER_EXEC
                       if entry['desktop_id'] == 'sentinel-guardian-websites.desktop' else
                       RECOVERY_EXEC if entry['desktop_id'] == RECOVERY_ID else
                      '/usr/lib/sentinel/venv/bin/python -I -m '
                      'sentinel.guardian_apps.launch ' + shlex.quote(entry['desktop_id']) + ' %U')
    for key in ('Actions', 'TryExec'):
        desktop.pop(key, None)
    for section in list(parser.sections()):
        if section.startswith('Desktop Action '):
            parser.remove_section(section)
    import io
    out = io.StringIO()
    parser.write(out, space_around_delimiters=False)
    return MARKER + out.getvalue()


def requires_shell_access(entry: dict) -> bool:
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    parser.read_string(entry['source'])
    actions = parser['Desktop Entry'].get('X-KDE-AuthorizeAction', '')
    return ('shell_access' in {a.strip() for a in actions.split(',')}
            or Path(entry.get('executable') or '').name == 'konsole')
